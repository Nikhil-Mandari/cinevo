let posterIndex = 0

const film = (seed: MovieSeed): Movie => ({
  ...seed,
  id: seed.slug,
  trailerUrl:
    seed.trailerUrl === undefined
      ? YOUTUBE_TRAILERS[seed.slug]
        ? `https://www.youtube.com/embed/${YOUTUBE_TRAILERS[seed.slug]}`
        : null
      : seed.trailerUrl,
  posterUrl:
    seed.posterUrl ??
    (YOUTUBE_TRAILERS[seed.slug]
      ? `https://i.ytimg.com/vi/${YOUTUBE_TRAILERS[seed.slug]}/hqdefault.jpg`
      : POSTER_IMAGES[posterIndex++ % POSTER_IMAGES.length]),
  createdAt: '2026-08-01T10:00:00.000Z',
})

